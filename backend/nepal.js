export function getProvince(name) {
  return NEPAL_PROVINCES.find((p) => p.name === name || p.headquarters === name);
}

export function getDistricts(provinceName) {
  const p = getProvince(provinceName);
  return p ? p.districts : [];
}

export function getCities(provinceName, districtName) {
  const p = getProvince(provinceName);
  if (!p) return [];
  const d = p.districts.find((x) => x.name === districtName);
  return d ? d.cities : [];
}
